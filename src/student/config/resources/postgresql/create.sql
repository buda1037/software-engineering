-- TEXT statt varchar(n): PostgreSQL speichert beide gleich, die Längen prüft die Anwendung.

-- https://www.postgresql.org/docs/current/manage-ag-tablespaces.html
SET default_tablespace = studentspace;

-- https://www.postgresql.org/docs/current/sql-createtable.html
-- https://www.postgresql.org/docs/current/datatype.html
-- https://www.postgresql.org/docs/current/sql-createtype.html
-- https://www.postgresql.org/docs/current/datatype-enum.html
CREATE TYPE gender AS ENUM ('MALE', 'FEMALE', 'DIVERSE');
CREATE TYPE studyprogram AS ENUM (
    'WIRTSCHAFTSINFORMATIK',
    'INTERNATIONALES_IT_BUSINESS',
    'DATA_SCIENCE'
);

CREATE TABLE IF NOT EXISTS student (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 1000) PRIMARY KEY,
                         -- impliziter Index als B-Baum durch UNIQUE
                         -- https://www.postgresql.org/docs/current/ddl-constraints.html#DDL-CONSTRAINTS-UNIQUE-CONSTRAINTS
    matriculation_number TEXT NOT NULL UNIQUE,
    username             TEXT UNIQUE,
    first_name           TEXT NOT NULL,
    last_name            TEXT NOT NULL,
    gender               gender,
                         -- https://www.postgresql.org/docs/current/datatype-datetime.html
    date_of_birth        DATE NOT NULL,
    email                TEXT NOT NULL UNIQUE,
    study_program        studyprogram NOT NULL,
    enrollment_date      DATE NOT NULL
);

-- default: btree
CREATE INDEX IF NOT EXISTS student_last_name_idx ON student(last_name);

CREATE TABLE IF NOT EXISTS address (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 1000) PRIMARY KEY,
    street       TEXT NOT NULL,
    house_number TEXT NOT NULL,
    postal_code  TEXT NOT NULL,
    city         TEXT NOT NULL,
    student_id   INTEGER NOT NULL UNIQUE REFERENCES student(id)
);

CREATE INDEX IF NOT EXISTS address_postal_code_idx ON address(postal_code);

CREATE TABLE IF NOT EXISTS exam_result (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 1000) PRIMARY KEY,
    module     TEXT NOT NULL,
               -- https://www.postgresql.org/docs/current/datatype-numeric.html#DATATYPE-NUMERIC-DECIMAL
               -- 2 Stellen insgesamt, davon 1 Nachkommastelle
    grade      NUMERIC(2, 1) NOT NULL,
    ects       INTEGER NOT NULL,
    exam_date  DATE NOT NULL,
    student_id INTEGER NOT NULL REFERENCES student(id)
);

CREATE INDEX IF NOT EXISTS exam_result_student_id_idx ON exam_result(student_id);
